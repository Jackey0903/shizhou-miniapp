const assert = require('assert')
const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '..')
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')

function main() {
  const login = read('cloudfunctions/userLogin/index.js')
  const loginPage = read('pages/login/login.js')
  const payment = read('cloudfunctions/createVipOrder/index.js')
  const paymentClient = read('utils/virtualPayment.js')
  const vipPage = read('pages/vip/vip.js')
  const supervisionPayPage = read('pages/supervision-pay/supervision-pay.js')
  const answers = read('cloudfunctions/submitAnswer/index.js')
  const questions = read('cloudfunctions/getQuestions/index.js')
  const materials = read('cloudfunctions/getMaterials/index.js')
  const exchange = read('cloudfunctions/exchangeMaterial/index.js')
  const plan = read('cloudfunctions/savePlan/index.js')
  const supervision = read('cloudfunctions/supervisionMatch/index.js')
  const reminder = read('cloudfunctions/studyReminderCenter/index.js')
  const oldPayment = read('cloudfunctions/wxpayFunctions/index.js')
  const oldReward = read('cloudfunctions/rewardVip/index.js')
  const mutualHelp = read('cloudfunctions/mutualHelpCenter/index.js')

  assert(login.includes('phonenumber.getPhoneNumber'), 'phone login must use the official code exchange API')
  assert(!login.includes('phoneData'), 'cloud login must not trust a client-provided phone number')
  assert(login.includes("action === 'updateProfile'"), 'profile updates must use a dedicated action')
  assert(loginPage.includes('e.detail.code'), 'phone login page must forward the one-time authorization code')
  assert(login.includes('expiresAt'), 'login tokens must expire')

  assert(payment.includes('validateRemoteOrder'), 'payment delivery must validate the remote order')
  assert(payment.includes('order_fee'), 'payment delivery must validate the paid amount')
  assert(payment.includes("source: 'xpay_goods_deliver_notify'"), 'official delivery callbacks must be reconciled')
  assert(payment.includes('xpay_refund_notify'), 'refund callbacks must be reconciled')
  assert(payment.includes('if (!latestOrder.benefitsGranted)'), 'refunds before delivery must not revoke unrelated benefits')
  assert(payment.includes('isDeliveryDone(granted)'), 'goods delivery notification must be idempotent')
  assert(!payment.includes('LEGACY_PLANS'), 'payment must not fall back to hard-coded plans')
  assert(paymentClient.includes('wx.requestVirtualPayment'), 'client must use official mini program virtual payment')
  assert(!read('utils/cloudApi.js').includes("name: 'queryVipOrder'"), 'order center must use the hardened virtual payment service')
  assert(paymentClient.includes('PAY_LOGIN_REQUIRED'), 'expired wx.login codes must be refreshed')
  assert(!vipPage.includes('FALLBACK_PLANS') && !supervisionPayPage.includes('FALLBACK_PLANS'), 'purchase pages must only display server plans')
  assert(oldPayment.includes('已停用'), 'legacy payment cloud function must remain disabled')

  assert(answers.includes('questionCorrectIndex'), 'answer records must persist a server-derived question snapshot')
  assert(answers.includes('assertQuestionAccess'), 'answer submission and review must enforce question-bank access')
  assert(answers.includes("action === 'list'"), 'study records must be scoped by a cloud function')
  assert(questions.includes('VIP专享'), 'locked question banks must be protected on the server')
  assert(plan.includes('canAccessCourse'), 'study plans must validate course access on the server')

  assert(materials.includes('delete safe[field]'), 'unowned material resource URLs must be hidden')
  assert(exchange.includes('runTransaction'), 'material redemption and coin deduction must be atomic')
  assert(exchange.includes('isVipActive'), 'VIP materials must check current entitlement on the server')
  assert(oldReward.includes('已停用'), 'legacy reward endpoint must remain disabled')

  assert(supervision.includes('pending_payment'), 'unpaid supervision profiles must not enter the active matching pool')
  assert(reminder.includes('supervisionExpireDate'), 'study reminders must require active supervision')
  assert(mutualHelp.includes('.map(toClientQuestion)'), 'mutual-help responses must use a public field allowlist')
  assert(mutualHelp.includes('DAILY_SUBMISSION_LIMIT'), 'mutual-help submissions must be rate limited')
  ;['getAllBook', 'getAllBookHome', 'getAllQuestion', 'getAllUser', 'getOpenid', 'getWallpapers'].forEach((name) => {
    const source = read(`cloudfunctions/${name}/index.js`)
    assert(source.includes('已停用'), `${name} legacy endpoint must remain disabled`)
    assert(!source.includes('cloud.database'), `${name} must not retain direct data access`)
  })
  console.log('critical security and business invariant checks passed')
}

main()
